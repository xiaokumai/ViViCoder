from utils.config_log import config, tracer
from langchain_core.prompts import PromptTemplate
from prompts.CoT import STSTEM_PROMPT, USER_INPUT, example_map
from utils.model_invoke import invoke_model



@tracer
def CoT(question: dict) -> str:
    """Chain of Thought reasoning strategy.

    Args:
        Question (str): The input question.

    Returns:
        str: The response generated by the model.
    """
    dataset_name = config.get("dataset", {}).get("name", "humaneval")
    example = example_map[dataset_name]
    

    user_input = PromptTemplate.from_template(USER_INPUT).format(example=example, prompt=question["prompt"])

    response = invoke_model(system_prompt=STSTEM_PROMPT, user_prompt=user_input)
        
    return response